"""把合并结果生成为 C 代码与构建条目。

产物（全部是增量）：

* 原函数定义名改为 `<target>__orig`（功能不减，原实现仍完整保留）。
* `kernel/sdkgen/<target>.c`：生成的同名包装，按合并顺序分发。
* `kernel/sdkgen/modules/<module-id>/…`：模块载荷源码的副本。
* `kernel/Kbuild` 末尾追加 `kernelsu-objs += …`。

模块入口函数约定：

* `inject`：签名与目标函数相同，返回 `int`；0 表示"没有意见"，继续下一个
  注入并最终执行原函数；非 0 短路，原函数不再执行。
* `replace`：签名与返回类型与目标函数相同，完全接管。
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .cparse import FuncDef
from .errors import GenerateError
from .merge import Plan, TargetPlan

SDK_DIR = "kernel/sdkgen"
MODULE_SUBDIR = "modules"
BANNER = """\
/*
 * Generated by ksuhook. DO NOT EDIT.
 * 真源是各模块的 hooks.toml 与 module.prop。
 */
"""


@dataclass(frozen=True)
class FileEdit:
    """对现有文件的就地改写：把函数定义名替换为 __orig。"""

    path: Path
    start: int
    end: int
    replacement: str


@dataclass(frozen=True)
class GeneratedFile:
    path: Path
    content: str


@dataclass(frozen=True)
class Generation:
    edits: tuple[FileEdit, ...]
    files: tuple[GeneratedFile, ...]
    kbuild_append: tuple[str, ...]


def orig_name(target: str) -> str:
    return f"{target}__orig"


def _entry_prototype(plan: Plan, func: FuncDef) -> str:
    entry = plan.hook.entry
    if plan.hook.mode == "inject":
        return f"extern int {entry}({func.param_decls()});"
    ret = func.ret if func.ret else "void"
    return f"extern {ret} {entry}({func.param_decls()});"


def _declares(text: str, name: str) -> bool:
    """头文件里是否已经声明了这个函数（够用的词法判断，不解析 C）。"""
    return re.search(rf"\b{re.escape(name)}\s*\(", text) is not None


def _call(entry: str, func: FuncDef) -> str:
    return f"{entry}({func.arg_names()})"


def _source_includes(func: FuncDef) -> list[str]:
    """沿用原文件的 include 列表，保证包装里用到的类型都有定义。"""
    includes: list[str] = []
    for line in func.path.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if stripped.startswith("#include"):
            includes.append(stripped)
    return includes


def _wrapper(
    plan: TargetPlan,
    func: FuncDef,
    hooks: dict[str, tuple[str, ...]],
    declared: frozenset[str],
) -> str:
    """hooks: 模块 id -> 随包复制进内核树的头文件列表。

    模块可以有多个头文件，入口函数不一定声明在字典序第一个里：全部包含，
    只有当这些头文件都没有声明入口时才退回 `extern` 原型（`declared` 为
    已在这些头文件里出现过的函数名）。
    """
    lines: list[str] = [BANNER]
    includes = _source_includes(func)
    if includes:
        lines.extend(includes)
        lines.append("")
    for module_id, headers in sorted(hooks.items()):
        for header in headers:
            lines.append(f'#include "modules/{module_id}/{header}"')
    if hooks:
        lines.append("")

    lines.append(f"/* {plan.target} 的原实现，位于 {func.path.as_posix().split('/kernel/')[-1]} */")
    lines.append(f"{func.ret} {orig_name(plan.target)}({func.param_decls()});")
    lines.append("")

    entries = [plan.replace] if plan.replace else list(plan.chain)
    for entry_plan in entries:
        assert entry_plan is not None
        lines.append(f"/* 模块 {entry_plan.module.id}: {entry_plan.hook.id} */")
        if entry_plan.hook.entry not in declared:
            lines.append(_entry_prototype(entry_plan, func))

    lines.append("")

    lines.append(f"{func.ret} {plan.target}({func.param_decls()})")
    lines.append("{")

    if plan.replace is not None:
        call = _call(plan.replace.hook.entry, func)
        lines.append(f"    {call};" if func.is_void else f"    return {call};")
    else:
        lines.append("    int __ret;")
        lines.append("")
        for entry_plan in plan.chain:
            lines.append(f"    /* 模块 {entry_plan.module.id}: {entry_plan.hook.id} */")
            lines.append(f"    __ret = {_call(entry_plan.hook.entry, func)};")
            lines.append("    if (__ret)")
            lines.append("        return __ret;")
        lines.append("")
        lines.append(f"    return {orig_name(plan.target)}({func.arg_names()});")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _module_files(plan: TargetPlan) -> list[GeneratedFile]:
    """把参与该函数的模块载荷复制进内核树，只复制一次。"""
    files: list[GeneratedFile] = []
    seen: set[str] = set()
    plans = ([plan.replace] if plan.replace else []) + list(plan.chain)
    for entry_plan in plans:
        if entry_plan is None or entry_plan.module.id in seen:
            continue
        seen.add(entry_plan.module.id)
        for src in sorted((entry_plan.module.root / "src").iterdir()):
            if src.suffix not in (".c", ".h"):
                continue
            files.append(
                GeneratedFile(
                    path=Path(SDK_DIR) / MODULE_SUBDIR / entry_plan.module.id / src.name,
                    content=src.read_text(encoding="utf-8", errors="replace"),
                )
            )
    return files


def generate(
    plans: tuple[TargetPlan, ...],
    funcs: dict[str, FuncDef],
    kbuild: Path,
    sdk_dir: str = SDK_DIR,
) -> Generation:
    edits: list[FileEdit] = []
    files: list[GeneratedFile] = []
    objects: list[str] = []

    for plan in plans:
        func = funcs.get(plan.target)
        if func is None:
            raise GenerateError("目标函数未在源码中找到定义", plan.target)
        if func.is_inline:
            raise GenerateError("inline 函数无法包装（GKI 下会被内联展开）", plan.target)
        if func.is_static:
            raise GenerateError(
                "static 函数只有内部链接，kernel/sdkgen 下的包装无法调用它；请 hook 一个外部可见的函数",
                plan.target,
            )

        edits.append(
            FileEdit(
                path=func.path,
                start=func.name_start,
                end=func.name_end,
                replacement=orig_name(plan.target),
            )
        )
        hooks_headers: dict[str, tuple[str, ...]] = {}
        declared: set[str] = set()
        module_files = _module_files(plan)
        for entry_plan in ([plan.replace] if plan.replace else list(plan.chain)):
            assert entry_plan is not None
            src_dir = entry_plan.module.root / "src"
            headers = sorted(p.name for p in src_dir.glob("*.h"))
            if headers:
                hooks_headers[entry_plan.module.id] = tuple(headers)
            for header in headers:
                text = (src_dir / header).read_text(encoding="utf-8", errors="replace")
                if _declares(text, entry_plan.hook.entry):
                    declared.add(entry_plan.hook.entry)

        files.append(
            GeneratedFile(
                path=Path(sdk_dir) / f"{plan.target}.c",
                content=_wrapper(plan, func, hooks_headers, frozenset(declared)),
            )
        )
        objects.append(f"sdkgen/{plan.target}.o")
        for extra in module_files:
            if extra not in files:
                files.append(extra)
        for entry_plan in ([plan.replace] if plan.replace else list(plan.chain)):
            assert entry_plan is not None
            for src in sorted((entry_plan.module.root / "src").glob("*.c")):
                obj = f"sdkgen/{MODULE_SUBDIR}/{entry_plan.module.id}/{src.stem}.o"
                if obj not in objects:
                    objects.append(obj)

    kbuild_append = tuple(f"kernelsu-objs += {obj}" for obj in objects)
    if kbuild_append and not kbuild.is_file():
        raise GenerateError("找不到 kernel/Kbuild", str(kbuild))

    return Generation(edits=tuple(edits), files=tuple(files), kbuild_append=kbuild_append)


def apply_edits(edits: tuple[FileEdit, ...], read) -> dict[Path, str]:
    """把改名编辑应用到原文；同一文件多处编辑按位置降序应用。"""
    by_path: dict[Path, list[FileEdit]] = {}
    for edit in edits:
        by_path.setdefault(edit.path, []).append(edit)

    result: dict[Path, str] = {}
    for path, path_edits in by_path.items():
        text = read(path)
        for edit in sorted(path_edits, key=lambda e: e.start, reverse=True):
            text = text[: edit.start] + edit.replacement + text[edit.end :]
        result[path] = text
    return result
